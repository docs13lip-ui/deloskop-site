// «Красная» зона ЗСК → исключение из ЕГРЮЛ: тексты [Право] 03.10 17:07 (claude/Право_ЗСК_красная_зона_исключение_тексты_03.10.md, разд. 1, 3)
const bezTegov = (h) => h.replace(/<script[\s\S]*?<\/script>/g, ' ').replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').replace(/&#8209;/g, '-').replace(/ /g, ' ');

test('/115-fz/zsk-zony-riska/: лид, H3 «могут исключить», абзац с п. 4 ст. 7.8 и п. 7 ст. 21.1, FAQ', () => {
  const h = chitat('115-fz/zsk-zony-riska/index.html');
  const t = bezTegov(h);
  assert.ok(t.includes('главный срок — 6 месяцев на заявление в межведомственную комиссию. Если его пропустить, компанию могут исключить из ЕГРЮЛ.'));
  assert.ok(h.includes('<h3 id="isklyuchenie">') && t.includes('Если не оспорить: компанию могут исключить из ЕГРЮЛ'));
  assert.ok(!/компанию исключат из ЕГРЮЛ/.test(t), 'исход не обещаем');
  assert.ok(t.includes('Банк России не позднее 10 рабочих дней передаёт сведения в налоговую для исключения компании из ЕГРЮЛ, а ИП — из ЕГРИП (п. 4 ст. 7.8 115-ФЗ).'));
  assert.ok(t.includes('если возражение подано, исключения не будет (пп. «г» п. 5 и п. 7 ст. 21.1 129-ФЗ).'));
  assert.ok(h.includes('"name": "Могут ли исключить компанию из ЕГРЮЛ за красную зону ЗСК?"'));
});

test('/115-fz/proverit-kontragenta-zsk-po-inn/: долг — с руководителей и участников, через суд; без «обычным путём»', () => {
  const t = bezTegov(chitat('115-fz/proverit-kontragenta-zsk-po-inn/index.html'));
  assert.ok(t.includes('Тогда требовать долг можно будет только с её руководителей и участников — и только через суд.'));
  assert.ok(!/обычным путём/.test(t));
});

