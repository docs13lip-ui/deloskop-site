// Норма: п. 5.2 ст. 7 115-ФЗ; «календарный год» и «отказ в операции по п. 11» — Информационное письмо Банка России от 28.03.2014 № 23 (cbr.ru).
'use strict';
const test = require('node:test');
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const KOREN = path.join(__dirname, '..');
const un = (s) => s.replace(/ /g, ' ').replace(/&nbsp;/g, ' ').replace(/&#8209;/g, '-').replace(/‑/g, '-').replace(/<[^>]+>/g, '');

test('разбор № 10: в «Где грань» — право расторгнуть договор после двух отказов, с нормой', () => {
  const t = un(fs.readFileSync(path.join(KOREN, 'praktika/115-fz/shtraf-banka-za-dokumenty-115-fz/index.html'), 'utf8'));
  assert.ok(t.includes('после двух и более отказов за год банк вправе расторгнуть договор счёта (п. 5.2 ст. 7 115-ФЗ)'), 'нет фразы о п. 5.2');
  assert.ok(t.includes('п. 5.2 ст. 7 115-ФЗ — право банка расторгнуть договор счёта после двух и более отказов в операции за календарный год'), 'нет строки «Где в законе»');
  // исход не обещаем, «обязан расторгнуть» — неверно: у банка право, а не обязанность
  assert.ok(!/обязан расторгнуть|расторгнет договор/.test(t), 'право банка подано как обязанность');
});
