// Словарь 222-ФЗ и ст. 152 ГК по всему сайту (п. 146; [Юрист 115-ФЗ] 29.09, разд. 3 и 7).
// Индекс — оценка признаков, а не кредитный рейтинг; связи — факт ЕГРЮЛ, а не «аффилированность».
// Полный словарь держит Паспорт (tests/pasport_kontragenta.test.js); здесь — то, чего не должно быть нигде.
// Слово «надёжн» пока вне словаря: зона Индекса «Надёжная» и тексты «Проверь счёт» ждут замены от [Данных] и [Юриста] (п. 146).
'use strict';
const test = require('node:test');
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const KOREN = path.join(__dirname, '..');
const SLOVAR = [
  [/рейтинг\S*\s+(над[её]жности|пл[ао]т[её]жеспособности)/i, '«рейтинг надёжности / платёжеспособности» — 222-ФЗ'],
  [/(?<!не\s)(?<!не&nbsp;)кредитн\S+\s+рейтинг/i, '«кредитный рейтинг» без отрицания — 222-ФЗ'],
  [/над[её]жная по делоскопу|самые над[её]жные|верят банки/i, 'позиционирование, отклонённое Планёркой 29.09'],
  [/вероятност\S* дефолта|не заплатит|риск невозврата/i, 'мнение о способности платить'],
  [/аффилирован|подконтрольн|номинальн|массов(ый|ого|ым) (директор|учредител)|техничк|однодневк/i, 'квалификация, которую даёт суд, а не мы (ст. 152 ГК)'],
  [/печать делоскопа|официальн\S* паспорт|паспорт ип\b/i, 'несуществующий статус (ч. 3 ст. 5 38-ФЗ)'],
  [/сделка ничтожна|договор недействителен|была банкротом/i, 'вывод суда'],
];
const faily = [];
(function obhod(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    if (e.name.startsWith('.') || ['node_modules', 'tests', 'сайт', 'fonts'].includes(e.name)) continue;
    const p = path.join(d, e.name);
    if (e.isDirectory()) obhod(p);
    else if (/\.(html|js|json)$/.test(e.name)) faily.push(p);
  }
})(KOREN);

test('словарь 222-ФЗ: ни на одной странице, в скрипте и ленте', () => {
  const osh = [];
  for (const f of faily) {
    const rel = path.relative(KOREN, f);
    // в самом Паспорте словарь — это регулярное выражение и дословная оговорка юриста; их проверяет тест Паспорта
    const t = fs.readFileSync(f, 'utf8').split('\n').filter((l) => !/SLOVAR_222 =|OPREDELENIE_INDEKSA =|function podval|заключение о надёжности или платёжеспособности/.test(l)).join('\n');
    for (const [re, pochemu] of SLOVAR) { const m = t.match(re); if (m) osh.push(rel + ': «' + m[0] + '» — ' + pochemu); }
  }
  assert.deepStrictEqual(osh, []);
});

test('словарь сам работает: ловит плохое, пропускает отрицание', () => {
  const hit = (s) => SLOVAR.some(([re]) => re.test(s));
  assert.ok(hit('собственный рейтинг надёжности 1–99'));
  assert.ok(hit('Так часто выглядят номинальные директора'));
  assert.ok(!hit('Это не кредитный рейтинг и не мнение о способности'));
  assert.ok(!hit('Руководитель по ЕГРЮЛ также руководит 12 компаниями'));
});
