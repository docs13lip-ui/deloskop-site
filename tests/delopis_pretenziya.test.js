// Делопись — претензия и срок до суда: текст [Право] 02.10.2026 13:15 (ч. 5 ст. 4 АПК РФ; ПП Пленума ВС № 18, п. 13, 22, 28).
// Запуск: node --test tests/delopis_pretenziya.test.js
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const D = fs.readFileSync(path.join(__dirname, '..', 'delopis', 'index.html'), 'utf8');
const sporu = (D.match(/S\('Разрешение споров', \[([\s\S]*?)\]\);/) || [])[1] || '';

test('раздел «Разрешение споров»: срок до суда, ответ раньше срока, электронный канал признан надлежащим', () => {
  assert.ok(sporu.includes("'До обращения в суд сторона направляет другой стороне претензию. Спор может быть передан в арбитражный суд по истечении ' + (on.sud10 ? '10 рабочих дней' : '30 календарных дней') + ' со дня направления претензии, а если ответ на претензию получен раньше — после его получения.'"));
  assert.ok(sporu.includes('Стороны признают надлежащим направление претензии через оператора электронного документооборота или на адрес электронной почты другой стороны, указанный в разделе «Реквизиты и подписи сторон», а также почтой по адресу, указанному в том же разделе.'));
  assert.ok(!D.includes('Срок ответа — 10 рабочих дней'), 'старый текст без срока обращения в суд');
  assert.ok(!/Пленум/.test(sporu), 'Пленум в договоре не упоминаем');
});

test('пункт sud10 включён по умолчанию и объяснён; в реквизитах сторон есть E-mail и адрес', () => {
  assert.ok(D.includes("{id: 'sud10', title: 'Срок до суда — 10 рабочих дней', always: true,"));
  assert.ok(D.includes('Срок до суда — 10 рабочих дней вместо 30 календарных по умолчанию (ч. 5 ст. 4 АПК РФ).'));
  assert.ok(D.includes("['E-mail', '']") && D.includes("rows.push(['Адрес', c.address]"));
  assert.ok(D.includes('<li><b>Срок до суда — 10 рабочих дней.</b>'));
});
