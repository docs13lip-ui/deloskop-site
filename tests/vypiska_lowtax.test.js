// vypiska-lowtax-v1 (05.10, [Ночные запуски]): тексты сигналов bigcash и lowtax в «Кому вы платите».
// bigcash — [Право · 115-ФЗ] 04.10 22:15 дословно: обязательный контроль по пп. 1 п. 1 ст. 6 115-ФЗ — только организации.
// lowtax — оговорка ПП РФ от 30.09.2026 № 1277 ([Право · Налоговый] 04.10 22:15); основная фраза с 18-МР — сверена 05.10.
// node --test tests/vypiska_lowtax.test.js
const test = require("node:test");
const assert = require("node:assert");
const E = require("../kontragenty-iz-vypiski/engine.js");

const A = "40702810900000000001";
function vypiska(...docs) {
  return E.analyze(E.parse(["1CClientBankExchange", "РасчСчет=" + A, "СекцияРасчСчет", "РасчСчет=" + A, "КонецРасчСчет", ...docs, "КонецФайла"].join("\n")));
}
function plat(n, summa, poluch, inn, naznach, schet) {
  return ["СекцияДокумент=Платежное поручение", "Номер=" + n, "Дата=01.09.2026", "Сумма=" + summa,
    "ПлательщикСчет=" + A, "ПлательщикИНН=7701234567", "Плательщик=ООО Ромашка",
    "ПолучательСчет=" + (schet || "40702810100000000099"), "ПолучательИНН=" + inn, "Получатель=" + poluch,
    "НазначениеПлатежа=" + naznach, "КонецДокумента"];
}

test("bigcash: организации — обязательный контроль, у ИП обязанности нет", () => {
  const S = "7707083893", B = "40702810000000000001";
  const d = (n, s, pa, ra, p) => `СекцияДокумент=Платежное поручение\nНомер=${n}\nДата=0${n}.07.2026\nСумма=${s}\nПлательщикСчет=${pa}\nПлательщикИНН=${pa === B ? S : ""}\nПолучательСчет=${ra}\nПолучательИНН=${ra === B ? S : "7728168971"}\nНазначениеПлатежа=${p}\nКонецДокумента`;
  const r = E.analyze(E.parse(["1CClientBankExchange", "РасчСчет=" + B, "СекцияРасчСчет", "РасчСчет=" + B, "КонецРасчСчет",
    d(1, "1500000.00", "20202810000000000001", B, "Взнос наличных. Торговая выручка"),
    d(2, "1200000.00", B, "30232810000000000001", "Снятие наличных по чеку на хозяйственные нужды"), "КонецФайла"].join("\n")));
  for (const b of r.flows.filter((f) => /^bigcash/.test(f.code))) {
    assert.match(b.text, /организаций банк по закону сообщает в Росфинмониторинг \(ст\. 6 115-ФЗ\)/);
    assert.match(b.text, /У ИП такой обязанности у банка нет/);
  }
  assert.ok(r.flows.some((f) => f.code === "bigcash"), JSON.stringify(r.flows));
});

test("исходник: старой фразы bigcash «банк сообщает о них» нет, новая — дословно", () => {
  const src = require("node:fs").readFileSync(require("node:path").join(__dirname, "../kontragenty-iz-vypiski/engine.js"), "utf8");
  assert.ok(!/По ст\. 6 115-ФЗ банк сообщает о них/.test(src));
  assert.ok(src.includes("О таких операциях организаций банк по закону сообщает в Росфинмониторинг (ст. 6 115-ФЗ) — это обязательный контроль, а не подозрение и не блокировка. У ИП такой обязанности у банка нет, но о происхождении крупных наличных он может спросить."));
});

test("lowtax: оговорка ПП № 1277 — у всех, без «приложите» и без «Wildberries»", () => {
  const r = vypiska(...plat(1, 2000000, "ООО Поставщик", "7707083893", "Оплата по договору 5 за товар, НДС не облагается"));
  const low = r.flows.find((f) => f.code === "lowtax");
  assert.ok(low, JSON.stringify(r.flows));
  assert.match(low.text, /постановление Правительства от 30\.09\.2026 № 1277/);
  assert.match(low.text, /сошлитесь на это в пояснении для банка/);
  assert.ok(!/приложите|Wildberries|Ozon|гарант/i.test(low.text));
  // основная фраза — с точным названием документа (18-МР действует, 0,9 % в п. о налогах — сверено 05.10)
  assert.match(low.text, /методические рекомендации ЦБ № 18-МР/);
});
