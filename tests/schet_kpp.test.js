// schet-kpp-v1: «Проверь счёт» (/proverit-schet/) — КПП принадлежит своему ИНН, «Сумма:» — сумма к оплате, банк с «к/с».
// Было: в «ИНН/КПП 7707083893/773601001» КПП стоял «до» ИНН (позиция по слову) → поставщику доставался КПП покупателя,
// при сверке с ЕГРЮЛ — ложное «КПП не совпадает»; у ИП (без КПП) — КПП покупателя; «Сумма: 100 000,00» не читалась
// (проверка ставки НДС молча пропускалась); «…в ПАО Сбербанк к/с 3010…» — банк терялся.
const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const html = fs.readFileSync(path.join(__dirname, '..', 'proverit-schet', 'index.html'), 'utf8');
const a = html.indexOf('/* ---------- контрольные числа ---------- */');
const b = html.indexOf('/* ---------- вывод ---------- */');
assert.ok(a > 0 && b > a, 'блок разбора найден');
const ctx = { money: (x) => x.toFixed(2) };
vm.createContext(ctx);
vm.runInContext(html.slice(a, b) + ';this.parse=parse;this.localChecks=localChecks;this.pickSeller=pickSeller;', ctx);
const P = (t) => JSON.parse(JSON.stringify(ctx.parse(t)));

const SBIS = `Счёт № 15 от 21.10.2026
Продавец: ООО «Ромашка»
ИНН/КПП 7707083893/773601001
Адрес: г. Москва
Покупатель: ООО «Лютик»
ИНН/КПП 7736050003/772801001
Получатель платежа: ООО «Ромашка» р/с 40702810938000012345 в ПАО Сбербанк к/с 30101810400000000225 БИК 044525225
Итого: 81 967,21
НДС 22%: 18 032,79
Всего с НДС: 100 000,00`;

const ELBA = `Счёт № 12 от 21 октября 2026 г.
Индивидуальный предприниматель Иванов Иван Иванович
ИНН 500100732259
Р/с 40802810938000012345
в АО «ТБанк»
БИК 044525974
Плательщик: ООО «Лютик», ИНН 7736050003, КПП 772801001
Итого: 50 000,00
Без НДС
Всего к оплате: 50 000,00`;

const MOE_DELO = `ООО «Ромашка»
ИНН 7707083893 КПП 773601001
р/сч 40702810938000012345
Банк ПАО Сбербанк
БИК 044525225 к/сч 30101810400000000225
СЧЕТ № 33 от 21.10.2026
Плательщик: ООО «Лютик» ИНН 7736050003 КПП 772801001
Наименование Кол-во Цена Сумма
Консультация 1 100 000,00 100 000,00
Сумма: 100 000,00
В т.ч. НДС (22%): 18 032,79`;

test('«ИНН/КПП 7707083893/773601001» — КПП поставщика, а не покупателя ниже', () => {
  const r = P(SBIS);
  assert.strictEqual(r.kpp, '773601001');
  assert.deepStrictEqual(r.inns.map((x) => [x.inn, x.kpp]), [['7707083893', '773601001'], ['7736050003', '772801001']]);
  const r2 = P('Продавец: ООО «Ромашка» ИНН/КПП 7707083893 / 773601001\nПокупатель: ООО «Лютик» ИНН/КПП 7736050003 / 772801001');
  assert.strictEqual(r2.kpp, '773601001');
});

test('у поставщика КПП не указан — чужой КПП не подставляем', () => {
  assert.strictEqual(P('Поставщик: ООО «Ромашка», ИНН 7707083893\nПокупатель: ООО «Лютик», ИНН 7736050003, КПП 772801001\nИтого к оплате: 10 000,00').kpp, null);
  const r = P(ELBA); // ИП — КПП нет
  assert.strictEqual(ctx.pickSeller(ctx.parse(ELBA)).inn, '500100732259');
  assert.strictEqual(r.kpp, null);
});

test('КПП у каждого ИНН свой — смена поставщика кнопкой ИНН берёт его КПП', () => {
  const r = ctx.parse('Плательщик: ООО «Лютик», ИНН 7736050003, КПП 772801001\nПолучатель: ООО «Ромашка», ИНН 7707083893, КПП 773601001');
  assert.strictEqual(r.kpp, '773601001');
  assert.strictEqual(r.inns.find((x) => x.inn === '7736050003').kpp, '772801001');
  assert.match(html, /var kp=sel&&sel\.kpp!==undefined\?sel\.kpp:r\.kpp/, 'сверка с ЕГРЮЛ — по КПП выбранного ИНН');
});

test('1С из PDF: ИНН и КПП в шапке банка, ниже — покупатель', () => {
  const t = 'ПАО СБЕРБАНК Г. МОСКВА БИК 044525225\nСч. № 30101810400000000225\nБанк получателя\nИНН 7707083893 КПП 773601001 Сч. № 40702810938000012345\nООО "Ромашка"\nПолучатель\nСчет на оплату № 123 от 21 октября 2026 г.\nПоставщик (Исполнитель): ООО "Ромашка", ИНН 7707083893, КПП 773601001\nПокупатель (Заказчик): ООО "Лютик", ИНН 7736050003, КПП 772801001\nИтого: 100 000,00\nВ том числе НДС: 18 032,79\nВсего к оплате: 100 000,00';
  const r = P(t);
  assert.strictEqual(r.kpp, '773601001');
  assert.strictEqual(r.total, 100000);
  assert.strictEqual(r.bank, 'ПАО СБЕРБАНК Г. МОСКВА');
});

test('«Сумма: 100 000,00» — сумма к оплате, ставка НДС проверяется', () => {
  const r = ctx.parse(MOE_DELO);
  assert.strictEqual(r.total, 100000);
  assert.strictEqual(r.kpp, '773601001');
  const n = ctx.localChecks(r, ctx.pickSeller(r)).filter((c) => c.title === 'НДС');
  assert.deepStrictEqual([...n.map((c) => c.st)], ['ok']);
  // заголовок колонки «Сумма» и «Сумма НДС» суммой к оплате не становятся
  assert.strictEqual(P('Наименование Кол-во Цена Сумма\n1 Товар 2 шт').total, null);
  assert.strictEqual(P('Сумма НДС: 18 032,79').total, null);
});

test('банк: «…в ПАО Сбербанк к/с 3010… БИК …» — название банка без корсчёта', () => {
  assert.strictEqual(P(SBIS).bank, 'ПАО Сбербанк');
  assert.strictEqual(P('Р/с 40702810938000000001 в ПАО Сбербанк, корр. счёт 30101810400000000225, БИК 044525225').bank, 'ПАО Сбербанк');
});
